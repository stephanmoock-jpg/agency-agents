#!/usr/bin/env python3
"""Erzeugt DesignTokens.swift aus tokens.json (light) + tokens.dark.json (dark).

    python3 gen_swift.py            # schreibt ./swift/DesignTokens.swift
Nie von Hand editieren: Tokens ändern, Script neu laufen lassen, contrast.py prüfen.
"""
import json, os, re

here = os.path.dirname(os.path.abspath(__file__))
light = json.load(open(os.path.join(here, "tokens.json")))
dark = json.load(open(os.path.join(here, "tokens.dark.json")))

def ident(name):
    parts = re.split(r"[-_]", name)
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return "_" + s if s[0].isdigit() else s

lines = [
    "// GENERATED by design/gen_swift.py from tokens.json + tokens.dark.json. Do not edit.",
    "import SwiftUI",
    "import UIKit",
    "",
    "private func hex(_ v: UInt32) -> UIColor {",
    "    UIColor(red: CGFloat((v >> 16) & 0xFF) / 255, green: CGFloat((v >> 8) & 0xFF) / 255,",
    "            blue: CGFloat(v & 0xFF) / 255, alpha: 1)",
    "}",
    "private func dynamic(_ l: UInt32, _ d: UInt32) -> Color {",
    "    Color(UIColor { $0.userInterfaceStyle == .dark ? hex(d) : hex(l) })",
    "}",
    "",
    "enum DS {",
    "    enum Palette {",
]
for k, v in light["color"].items():
    d = dark["color"].get(k, v)
    lines.append("        static let %s = dynamic(0x%s, 0x%s)" % (ident(k), v.lstrip("#").upper(), d.lstrip("#").upper()))
lines += [
    "        static func grade(_ g: Int) -> Color {",
    "        switch g { case 1: grade1; case 2: grade2; case 3: grade3; case 4: grade4; case 5: grade5;",
    "                   case 6: grade6; case 7: grade7; case 8: grade8; default: grade9 } }",
    "        static func onGrade(_ g: Int) -> Color { g >= 9 ? onGrade9 : onGrade }",
    "        static func region(_ id: String) -> Color {",
    "        switch id { case \"push\": regionPush; case \"pull\": regionPull; case \"core\": regionCore;",
    "                    case \"legs\": regionLegs; case \"shoulders\": regionShoulders; default: regionGrip } }",
    "    }",
    "    enum Space {",
]
for i, v in enumerate(light["space"]):
    lines.append("        static let s%d: CGFloat = %d" % (i, v))
lines += ["    }", "    enum Radius {"]
for k, v in light["radius"].items():
    lines.append("        static let %s: CGFloat = %d" % (ident(k), v))
lines += ["    }", "    enum Layout {"]
for k, v in light["layout"].items():
    if isinstance(v, (int, float)):
        lines.append("        static let %s: CGFloat = %s" % (ident(k), v))
lines += [
    "    }",
    "    enum Typo {",
    "        static let caption = Font.caption.weight(.medium)",
    "        static let footnote = Font.footnote",
    "        static let body = Font.body",
    "        static let headline = Font.headline",
    "        static let title = Font.title2.weight(.bold)",
    "        static let large = Font.largeTitle.weight(.bold)",
    "        static let grade = Font.system(.largeTitle, design: .rounded).weight(.heavy)",
    "        static let power = Font.system(.title, design: .rounded).weight(.bold).monospacedDigit()",
    "    }",
    "    enum Motion {",
    "        static let fast = Animation.easeOut(duration: 0.15)",
    "        static let base = Animation.easeInOut(duration: 0.25)",
    "        static let reveal = Animation.spring(response: 0.5, dampingFraction: 0.75)",
    "        /// Bei Reduce Motion: kurzer Crossfade statt Spring.",
    "        static func reveal(reduced: Bool) -> Animation { reduced ? .easeInOut(duration: 0.2) : reveal }",
    "    }",
    "}",
    "",
]
os.makedirs(os.path.join(here, "swift"), exist_ok=True)
open(os.path.join(here, "swift", "DesignTokens.swift"), "w").write("\n".join(lines))
print("wrote swift/DesignTokens.swift (%d colors)" % len(light["color"]))
